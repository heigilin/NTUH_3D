const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8').replace(/<!--[\s\S]*?-->/g, '');
const files = [...html.matchAll(/src="(js\/[^"?]+)(?:\?[^" ]*)?"/g)].map(m => m[1])
  .filter(p => /js\/data\/(campus-data|rooms-data|ward-3d-layout-data|ward-bed-ids|ward-proportion-review-data)\.js$/.test(p) || /js\/ward-(source-|plan-layout|door-layout|plan-geometry|plan-2d)/.test(p));
const c = { window: {}, console }; vm.createContext(c);
for (const p of files) vm.runInContext(fs.readFileSync(p, 'utf8'), c, { filename: p });
const w = c.window; w.WardPlanGeometry.prepare(w.WARD_3D_LAYOUT_DATA, w.WardPlanGeometry.rawCorridors);
const l = w.WARD_3D_LAYOUT_DATA.E01_MAIN['4F'];
const rooms = l.rooms.filter(r => r.ward === '04D1');
assert.equal(rooms.length, 9);
assert(rooms.every(r=>r.sourcePlan==='素材/04D1.png' && r.geometryBasis==='engineering-image-rectangular-approximation'));
for(const r of rooms) assert(Math.abs(r.bounds.width/r.bounds.depth-r.sourceRect.w/r.sourceRect.h)<1e-8,'engineering aspect ratio changed');
assert(rooms.every(r=>r.bedBounds && r.sourceBedRect),'safe bed zones missing');
assert(rooms.every(r=>r.door?.validation==='clear-access'),'room door access unresolved');
const room = code => rooms.find(r => r.roomCode === code);
assert.equal(JSON.stringify(rooms.filter(r => !r.upper).sort((a,b)=>a.bounds.x-b.bounds.x).map(r=>r.roomCode)), JSON.stringify(['01','02','03','05','06','07']));
assert.equal(JSON.stringify(rooms.filter(r => r.upper).sort((a,b)=>a.bounds.x-b.bounds.x).map(r=>r.roomCode)), JSON.stringify(['08','09','10']));
const beds = l.beds.filter(b => b.ward === '04D1');
assert.equal(beds.length, 10); assert(beds.every(b => !b.symbolOnly));
assert.equal(beds.filter(b => b.roomCode==='01').length, 2);
const registry = Object.values(w.WARD_BED_IDS['04D1']).flat().sort();
assert.equal(JSON.stringify(beds.map(b=>b.bedId).sort()), JSON.stringify(registry));
assert.equal(l.sourceUnplacedBeds.filter(b => b.ward === '04D1').length, 0);
const station = l.nursingStations.find(n => n.ward==='04D1');
assert(station && station.bounds.x < room('08').bounds.x && station.bounds.z < room('01').bounds.z);
const anteroom=l.facilities.find(f=>f.ward==='04D1'&&f.name==='07前室');
assert(anteroom && Math.abs(anteroom.bounds.x-room('07').bounds.x)<1e-6 && anteroom.bounds.z<room('07').bounds.z);
const supply=l.facilities.find(f=>f.ward==='04D1'&&f.name==='儀器室');
assert(supply && supply.bounds.x>room('10').bounds.x);
const rect = q => w.WardPlanGeometry.rect(q.bounds);
const spaces = [...l.rooms, ...l.facilities, ...l.nursingStations].filter(q => q.ward === '04D1');
for (let i=0; i<spaces.length; i++) for (let j=i+1; j<spaces.length; j++) assert(!w.WardPlanGeometry.hit(rect(spaces[i]), rect(spaces[j])), 'space overlap '+(spaces[i].roomCode||spaces[i].name)+' / '+(spaces[j].roomCode||spaces[j].name));
for (const r of rooms) for (const lane of l.sourceTraceCorridors) assert(!w.WardPlanGeometry.hit(rect(r), rect(lane)), 'bed bay overlaps circulation');
const scene = w.WardPlan2D.scene('E01_MAIN', '4F', '04D1');
assert.equal(scene.rooms.length, 9); assert.equal(scene.beds.length, 10);
console.log(JSON.stringify({rooms:9,beds:10,registryIdsPreserved:true,unplaced:0,spaceOverlaps:0,roomCorridorOverlaps:0,shared2DModel:true,geometryBasis:'engineering-image-rectangular-approximation'}));
